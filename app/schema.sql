CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(32) NOT NULL,
 password_hash VARCHAR(255) NULL,
 is_bot TINYINT(1) NOT NULL DEFAULT 0,
 bot_number INT UNSIGNED NULL,
 personality VARCHAR(24) NOT NULL DEFAULT 'scrapper',
 avatar INT UNSIGNED NOT NULL DEFAULT 0,
 rating INT NOT NULL DEFAULT 1000,
 points INT UNSIGNED NOT NULL DEFAULT 0,
 wins INT UNSIGNED NOT NULL DEFAULT 0,
 losses INT UNSIGNED NOT NULL DEFAULT 0,
 games INT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_seen DATETIME NULL,
 UNIQUE KEY username_unique (username),
 UNIQUE KEY bot_number_unique (bot_number),
 KEY ranking (rating, wins),
 KEY bots (is_bot, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS rooms (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(64) NOT NULL,
 host_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'waiting',
 turn INT UNSIGNED NOT NULL DEFAULT 0,
 state LONGTEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 starts_at DATETIME NOT NULL,
 next_turn_at DATETIME NULL,
 finished_at DATETIME NULL,
 KEY active_rooms (status, next_turn_at),
 KEY finished (finished_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS memberships (
 user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 room_id BIGINT UNSIGNED NOT NULL,
 KEY room_members (room_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS results (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 room_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 won TINYINT(1) NOT NULL,
 rating_delta INT NOT NULL,
 points INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY one_result (room_id,user_id),
 KEY player_history (user_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 room_id BIGINT UNSIGNED NULL,
 user_id BIGINT UNSIGNED NULL,
 body VARCHAR(300) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY room_messages (room_id,id),
 KEY created_messages (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings (
 name VARCHAR(64) NOT NULL PRIMARY KEY,
 value TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS rate_limits (
 key_name VARCHAR(64) NOT NULL PRIMARY KEY,
 hits INT UNSIGNED NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 KEY expiration (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
